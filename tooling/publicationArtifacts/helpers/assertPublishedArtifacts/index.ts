import { lstat, readdir } from 'node:fs/promises'
import nodePath from 'node:path'

import { digestFile } from '../../../markdownPrerender/helpers/artifactDigest/index.ts'
import type { DigestMap, PublishedOptions } from '../../types.ts'

type AssertOptions = PublishedOptions & {
  xmlPaths: ReadonlySet<string>
  approved: DigestMap
}
type FileScan = { files: string[]; irregular: string[] }

const SITEMAP_DIR = 'sitemaps'
const SITEMAP_ROOT = '/sitemap.xml'

function isMissing(error: unknown): boolean {
  return error instanceof Error && 'code' in error && error.code === 'ENOENT'
}

async function scanSitemapFiles(publicDir: string): Promise<FileScan> {
  const scan: FileScan = { files: [], irregular: [] }
  try {
    const entries = await readdir(nodePath.join(publicDir, SITEMAP_DIR), {
      recursive: true,
      withFileTypes: true
    })
    for (const entry of entries) {
      const relative = nodePath.relative(
        publicDir,
        nodePath.join(entry.parentPath, entry.name)
      )
      const path = `/${relative.split(nodePath.sep).join('/')}`
      if (entry.isDirectory()) continue
      const target = entry.isFile() ? scan.files : scan.irregular
      target.push(path)
    }
  } catch (error) {
    if (!isMissing(error)) throw error
  }
  try {
    const root = await lstat(nodePath.join(publicDir, SITEMAP_ROOT))
    const target = root.isFile() ? scan.files : scan.irregular
    target.push(SITEMAP_ROOT)
  } catch (error) {
    if (!isMissing(error)) throw error
  }
  return scan
}

async function findChangedFiles({
  publicDir,
  approved
}: Pick<AssertOptions, 'publicDir' | 'approved'>): Promise<string[]> {
  const problems: string[] = []
  for (const [path, digest] of approved) {
    try {
      const actual = await digestFile(nodePath.join(publicDir, path))
      if (actual.size !== digest.size || actual.hash !== digest.hash) {
        problems.push(`${path} (content differs from the approved artifact)`)
      }
    } catch (error) {
      if (!isMissing(error)) throw error
      problems.push(`${path} (missing from the static output)`)
    }
  }
  return problems
}

// O diretório publicado é confrontado com o registro do Nitro: uma cópia de
// `public/` em `sitemaps/` ou um `sitemap.xml` solto sombreariam rotas dinâmicas
// antes da função, e nada neles passaria pelo prerender.
export async function assertPublishedArtifacts({
  publicDir,
  prerenderedRoutes,
  xmlPaths,
  approved
}: AssertOptions): Promise<void> {
  const written = new Map(prerenderedRoutes.map(route => [route.route, route]))
  const { files, irregular } = await scanSitemapFiles(publicDir)
  const found = new Set(files)
  const problems = [
    ...irregular.map(path => `${path} (not a regular file)`),
    ...files
      .filter(path => !xmlPaths.has(path))
      .map(path => `${path} (would shadow a dynamic sitemap route)`),
    ...[...xmlPaths]
      .filter(path => !found.has(path) || written.get(path)?.fileName !== path)
      .map(path => `${path} (not generated by the prerender)`),
    ...(await findChangedFiles({ publicDir, approved }))
  ]
  if (problems.length > 0) {
    throw new Error(`Invalid publication output: ${problems.join(', ')}`)
  }
}
